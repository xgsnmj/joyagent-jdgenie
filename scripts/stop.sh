#!/bin/bash
# ============================================
# 华创证券智能体底座 - 停止脚本 (Linux/Mac)
# ============================================

set -e

echo "=========================================="
echo "  华创证券智能体底座 - 停止服务"
echo "=========================================="
echo ""

# 询问是否停止
read -p "确认要停止所有服务吗？(y/n) " -n 1 -r
echo ""
if [[ ! $REPLY =~ ^[Yy]$ ]]; then
    echo "❌ 已取消停止"
    exit 0
fi

echo "🛑 正在停止所有服务..."
echo ""

# 停止服务
docker-compose down

echo ""
echo "✅ 所有服务已停止"
echo ""
echo "如需删除数据卷，请执行:"
echo "  docker-compose down -v"
echo ""
